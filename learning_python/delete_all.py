def delete_all(my_list, target):
    while target in my_list:
        my_list.remove(target)
    return my_list


print(delete_all([4, 4, 4], 4))




#### VERY IMPORTANT NOTE: THIS IS THE OCCASION WEHRE WE SHOULD HAVE USED WHILE LOOP INSTEAD OF FOR LOOP. BECAUSE WE ARE CHANGING THE LIST WHILE ITERATING OVER IT. THIS IS A VERY COMMON MISTAKE. ALWAYS USE WHILE LOOP WHEN YOU ARE CHANGING THE LIST WHILE ITERATING OVER IT. FOR LOOP IS NOT SAFE IN THIS CASE. IT WILL SKIP ELEMENTS AND CAUSE UNEXPECTED BEHAVIOR.

### WE CANNOT USE FOR LOOP BECUASE WHEN WE USE FOR LOOP, PYTHON WILL BE KEEPING TRACK OF THE INDEX AND WHEN WE REMOVE AN ELEMENT, THE INDEX WILL BE SHIFTED AND WE WILL SKIP THE NEXT ELEMENT. THIS IS A VERY COMMON MISTAKE.